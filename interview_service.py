# ------------------------------------------------------------------
# AGGREGATION  (same logic as the original aggregate.py)
# ------------------------------------------------------------------
SCORE_FIELDS = ["technical_skills", "problem_solving", "communication", "culture_fit"]
FIELD_LABELS = {
    "technical_skills": "Technical Skills",
    "problem_solving": "Problem Solving",
    "communication": "Communication",
    "culture_fit": "Culture Fit",
}
REC_TO_SCORE = {"Strong Hire": 4, "Hire": 3, "No Hire": 2, "Strong No Hire": 1}
SCORE_TO_REC = {v: k for k, v in REC_TO_SCORE.items()}
POSITIVE_RECS = {"Hire", "Strong Hire"}
NEGATIVE_RECS = {"No Hire", "Strong No Hire"}


def _final_recommendation(recs):
    has_positive = any(r in POSITIVE_RECS for r in recs)
    has_negative = any(r in NEGATIVE_RECS for r in recs)
    if has_positive and has_negative:
        return "Split Decision - Needs Discussion"
    avg = statistics.mean(REC_TO_SCORE[r] for r in recs)
    rounded = min(max(round(avg), 1), 4)
    return SCORE_TO_REC[rounded]


def consolidate(rows):
    by_candidate = defaultdict(list)
    for row in rows:
        by_candidate[row["candidate_name"]].append(row)

    results = []
    for candidate, entries in by_candidate.items():
        position = entries[-1]["position"]
        dim_avgs = {
            FIELD_LABELS[f]: round(statistics.mean(e[f] for e in entries), 2)
            for f in SCORE_FIELDS
        }
        overall_avg = round(statistics.mean(dim_avgs.values()), 2)
        recs = [e["recommendation"] for e in entries]
        final_rec = _final_recommendation(recs)

        results.append({
            "candidate": candidate,
            "position": position,
            "rounds_completed": len(entries),
            "dimension_averages": dim_avgs,
            "overall_average": overall_avg,
            "final_recommendation": final_rec,
        })

    results.sort(key=lambda r: r["overall_average"], reverse=True)
    return results



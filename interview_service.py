def _row_to_dict(cursor, row):
    columns = [d[0].lower() for d in cursor.description]
    return dict(zip(columns, row))


def get_all_feedback():
    conn = get_connection()
    try:
        cur = conn.cursor()
        cur.execute("SELECT * FROM interview_feedback ORDER BY interview_date ASC, id ASC")
        return [_row_to_dict(cur, r) for r in cur.fetchall()]
    finally:
        conn.close()


def get_candidate_feedback(candidate_name: str):
    conn = get_connection()
    try:
        cur = conn.cursor()
        cur.execute(
            "SELECT * FROM interview_feedback WHERE candidate_name = :1 ORDER BY interview_date ASC, id ASC",
            [candidate_name],
        )
        return [_row_to_dict(cur, r) for r in cur.fetchall()]
    finally:
        conn.close()


def get_feedback_by_id(feedback_id: int):
    conn = get_connection()
    try:
        cur = conn.cursor()
        cur.execute("SELECT * FROM interview_feedback WHERE id = :1", [feedback_id])
        row = cur.fetchone()
        return _row_to_dict(cur, row) if row else None
    finally:
        conn.close()


def insert_feedback(data: dict):
    conn = get_connection()
    try:
        cur = conn.cursor()
        cur.execute(
            """INSERT INTO interview_feedback
               (candidate_name, position, interview_round, interviewer_name, interview_date,
                technical_skills, problem_solving, communication, culture_fit, recommendation, comments)
               VALUES (:candidate_name, :position, :interview_round, :interviewer_name, :interview_date,
                       :technical_skills, :problem_solving, :communication, :culture_fit, :recommendation, :comments)""",
            data,
        )
        conn.commit()
    finally:
        conn.close()


def update_feedback(feedback_id: int, data: dict):
    conn = get_connection()
    try:
        cur = conn.cursor()
        cur.execute(
            """UPDATE feedback SET
                   candidate_name = :candidate_name,
                   position = :position,
                   interview_round = :interview_round,
                   interviewer_name = :interviewer_name,
                   interview_date = :interview_date,
                   technical_skills = :technical_skills,
                   problem_solving = :problem_solving,
                   communication = :communication,
                   culture_fit = :culture_fit,
                   recommendation = :recommendation,
                   comments = :comments
               WHERE id = :id""",
            {**data, "id": feedback_id},
        )
        conn.commit()
    finally:
        conn.close()


def delete_candidate(candidate_name: str):
    conn = get_connection()
    try:
        cur = conn.cursor()
        cur.execute("DELETE FROM interview_feedback WHERE candidate_name = :1", [candidate_name])
        conn.commit()
    finally:
        conn.close()


def delete_feedback_entry(feedback_id: int):
    conn = get_connection()
    try:
        cur = conn.cursor()
        cur.execute("DELETE FROM interview_feedback WHERE id = :1", [feedback_id])
        conn.commit()
    finally:
        conn.close()


